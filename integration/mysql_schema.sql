-- =========================================================================
-- AI Adaptive Tourism Companion: MySQL Relational Database Schema
-- Designed for Spring Boot (JPA / Hibernate) and Python AI Microservice
-- =========================================================================

CREATE DATABASE IF NOT EXISTS `ai_tourism_db` 
CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE `ai_tourism_db`;

-- 1. Users Table
CREATE TABLE IF NOT EXISTS `users` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `email` VARCHAR(191) NOT NULL UNIQUE,
    `full_name` VARCHAR(150) NOT NULL,
    `preferred_currency` VARCHAR(10) DEFAULT 'INR',
    `preferred_language` VARCHAR(50) DEFAULT 'English',
    `accessibility_profile` JSON NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 2. Trips Table
CREATE TABLE IF NOT EXISTS `trips` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `user_id` BIGINT NOT NULL,
    `destination` VARCHAR(255) NOT NULL,
    `duration_days` INT NOT NULL DEFAULT 3,
    `total_budget` DECIMAL(12, 2) NOT NULL,
    `group_size` INT NOT NULL DEFAULT 1,
    `traveler_type` VARCHAR(50) DEFAULT 'solo', -- solo, couple, family, friends, college_group, seniors
    `pace_preference` VARCHAR(50) DEFAULT 'moderate', -- relaxed, moderate, fast_paced
    `start_date` DATE NULL,
    `end_date` DATE NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT `fk_trips_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 3. Itineraries Table (Generated by AI)
CREATE TABLE IF NOT EXISTS `itineraries` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `trip_id` BIGINT NOT NULL,
    `trip_title` VARCHAR(255) NOT NULL,
    `total_estimated_cost` DECIMAL(12, 2) NOT NULL,
    `eco_score` INT NOT NULL DEFAULT 85,
    `green_transport_percent` INT NOT NULL DEFAULT 80,
    `safety_rating` VARCHAR(100) DEFAULT 'High',
    `is_active` BOOLEAN DEFAULT TRUE,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT `fk_itinerary_trip` FOREIGN KEY (`trip_id`) REFERENCES `trips` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 4. Day Plans Table
CREATE TABLE IF NOT EXISTS `day_plans` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `itinerary_id` BIGINT NOT NULL,
    `day_number` INT NOT NULL,
    `focus_theme` VARCHAR(255) NOT NULL,
    `transit_mode` VARCHAR(150) DEFAULT 'Metro / Walking',
    `total_day_cost` DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    CONSTRAINT `fk_day_itinerary` FOREIGN KEY (`itinerary_id`) REFERENCES `itineraries` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 5. Activities Table
CREATE TABLE IF NOT EXISTS `activities` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `day_plan_id` BIGINT NOT NULL,
    `activity_uid` VARCHAR(64) NOT NULL,
    `title` VARCHAR(255) NOT NULL,
    `time_slot` ENUM('Morning', 'Afternoon', 'Evening') NOT NULL,
    `category` VARCHAR(50) NOT NULL,
    `location` VARCHAR(255) NOT NULL,
    `estimated_cost` DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    `duration_hours` DECIMAL(4, 2) NOT NULL DEFAULT 2.50,
    `is_indoor` BOOLEAN NOT NULL DEFAULT FALSE,
    `description` TEXT NULL,
    `accessibility_features` JSON NULL,
    `eco_friendly` BOOLEAN DEFAULT TRUE,
    CONSTRAINT `fk_activity_day` FOREIGN KEY (`day_plan_id`) REFERENCES `day_plans` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 6. Disruption & Adaptation Logs (Real-time AI Replanning)
CREATE TABLE IF NOT EXISTS `disruption_logs` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `itinerary_id` BIGINT NOT NULL,
    `day_number` INT NOT NULL,
    `time_slot` VARCHAR(50) NOT NULL,
    `disruption_type` VARCHAR(50) NOT NULL, -- weather, traffic, crowd_surge, attraction_closed
    `description` TEXT NOT NULL,
    `severity` VARCHAR(20) DEFAULT 'medium',
    `original_activity_title` VARCHAR(255) NOT NULL,
    `substituted_activity_title` VARCHAR(255) NOT NULL,
    `reason_for_change` TEXT NOT NULL,
    `budget_variance` DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT `fk_disruption_itinerary` FOREIGN KEY (`itinerary_id`) REFERENCES `itineraries` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 7. Group Trips & Consensus Table
CREATE TABLE IF NOT EXISTS `group_trips` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `trip_id` BIGINT NOT NULL,
    `recommended_shared_budget` DECIMAL(12, 2) NOT NULL,
    `cost_per_person` DECIMAL(12, 2) NOT NULL,
    `consensus_summary` TEXT NOT NULL,
    `selected_accommodation` JSON NULL,
    `selected_transit_mode` VARCHAR(150) NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT `fk_group_trip` FOREIGN KEY (`trip_id`) REFERENCES `trips` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 8. Group Members & Voting Table
CREATE TABLE IF NOT EXISTS `group_members` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `group_trip_id` BIGINT NOT NULL,
    `member_name` VARCHAR(150) NOT NULL,
    `max_budget` DECIMAL(12, 2) NOT NULL,
    `allocated_split` DECIMAL(12, 2) NOT NULL,
    `interests` JSON NOT NULL,
    `accessibility_needs` JSON NULL,
    CONSTRAINT `fk_group_members` FOREIGN KEY (`group_trip_id`) REFERENCES `group_trips` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 9. Smart Packing Checklists
CREATE TABLE IF NOT EXISTS `packing_checklists` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `trip_id` BIGINT NOT NULL,
    `weather_summary` VARCHAR(255) NOT NULL,
    `total_items` INT NOT NULL,
    `checklist_json` JSON NOT NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT `fk_packing_trip` FOREIGN KEY (`trip_id`) REFERENCES `trips` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 10. Landmark Vision AI Scans
CREATE TABLE IF NOT EXISTS `landmark_scans` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `user_id` BIGINT NULL,
    `image_hash_or_hint` VARCHAR(255) NOT NULL,
    `recognized_landmark` VARCHAR(255) NOT NULL,
    `confidence_score` DECIMAL(4, 3) NOT NULL,
    `historical_summary` TEXT NOT NULL,
    `audio_script` TEXT NOT NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
