export function generateBookingLinks(hotelName, cityName, isIntl = false) {
  const cleanCity = (cityName || "Zurich").split("(")[0].split(",")[0].trim();
  const encodedCity = encodeURIComponent(cleanCity);
  const encodedHotel = encodeURIComponent(hotelName);
  const query = encodeURIComponent(`${hotelName} ${cleanCity}`);

  // 1. MakeMyTrip Direct Property Search within City (Validates 100% on MakeMyTrip)
  const makemytrip = `https://www.makemytrip.com/hotels/hotel-listing/?city=${encodedCity}&searchText=${encodedHotel}`;
  
  // 2. MakeMyTrip All Hotels in City
  const mmtCity = `https://www.makemytrip.com/hotels/hotel-listing/?city=${encodedCity}`;

  // 3. Google Hotels Meta Search (Aggregates MakeMyTrip, Agoda, Booking.com)
  const google = `https://www.google.com/travel/hotels?q=${encodeURIComponent(hotelName + " " + cleanCity + " MakeMyTrip")}`;

  // 4. Booking.com
  const booking = `https://www.booking.com/searchresults.html?ss=${query}`;

  return {
    primary_url: makemytrip,
    makemytrip_url: makemytrip,
    makemytrip_city_url: mmtCity,
    google_hotels_url: google,
    booking_url: booking
  };
}

export function getHotelsForDay(destKey = "switzerland", dayNumber = 1, destination = "", isIntl = false) {
  let destHotels = HOTELS_DATABASE[destKey];
  if (!destHotels || destHotels.length === 0) {
    destHotels = getHotelsForDestination(destKey, destination || destKey);
  }
  if (!Array.isArray(destHotels) || destHotels.length === 0) return [];

  const targetCity = getDaySpecificCity(destKey, dayNumber);

  // Filter for hotels matching this specific day
  let matching = destHotels.filter(h => h.day === dayNumber);
  
  if (matching.length === 0) {
    const cycleDay = ((dayNumber - 1) % 5) + 1;
    matching = destHotels.filter(h => h.day === cycleDay);
  }

  if (matching.length === 0) matching = destHotels;

  return matching.map(h => ({
    ...h,
    city: targetCity,
    booking_links: generateBookingLinks(h.name, targetCity, isIntl)
  }));
}

